@torch.no_grad()
def _run_validation(
    model, geo_embedding, noise_scheduler,
    val_dataloader, accelerator, weight_dtype,
    args, global_step, epoch, norm_stats,
):
    """
    在验证集上计算:
      - 全图 RMSE（QL5海洋区域）
      - 仅补全区 RMSE（Perlin缺失区 ∩ QL5海洋）
    推理方式：DDIM，ddpm_num_inference_steps 步。
    可视化：每次验证保存 vis_num_samples 张对比图。
    """
    model.eval()
    geo_embedding.eval()

    # 构建 DDIM 调度器（与训练调度器配置一致）
    ddim_scheduler = LocalDDIMScheduler(
        num_train_timesteps=args.ddpm_num_steps,
        num_mask_timesteps=args.ddpm_mask_num_steps,
        prediction_type=args.prediction_type,
    )
    ddim_scheduler.set_timesteps(args.ddpm_num_inference_steps)

    all_rmse_global  = []
    all_rmse_inpaint = []
    vis_saved        = False   # 只保存第一个batch的可视化

    val_perlin_sig = 5   # 验证时固定中等频率

    t_min   = norm_stats["t_min"]
    t_scale = norm_stats["t_max"] - norm_stats["t_min"]

    for batch_idx, batch in enumerate(val_dataloader):
        sst          = batch["sst"].to(dtype=weight_dtype, device=accelerator.device)
        era5         = batch["era5"].to(dtype=weight_dtype, device=accelerator.device)
        land_mask    = batch["land_mask"].to(dtype=weight_dtype, device=accelerator.device)
        static_valid = batch["static_valid"].to(dtype=weight_dtype, device=accelerator.device)
        center_lat   = batch["center_lat"].to(accelerator.device)
        center_lon   = batch["center_lon"].to(accelerator.device)
        day_of_year  = batch["day_of_year"].to(accelerator.device)

        B, _, H, W = sst.shape

        perlin_mask = generate_perlin_noise_2d(
            (B, H, W), rand=True, sig=val_perlin_sig
        ).to(sst.device)  # [B, 1, H, W]

        geo_emb = geo_embedding(center_lat, center_lon, day_of_year)

        # ---- DDIM 去噪推理 ----
        # 从纯噪声出发，仅对缺失区域去噪（已知区域用 clean SST 覆盖）
        noisy_sst = torch.randn_like(sst)

        random_steps, m_steps, om_steps = set_random_steps(args)
        ddim_scheduler.random_steps = random_steps
        ddim_scheduler.m_steps      = m_steps
        ddim_scheduler.om_steps     = om_steps

        # 用最大时间步初始化 set_variables（推理阶段用固定全噪声时间步）
        init_timestep = torch.full((B,), args.ddpm_num_steps - 1,
                                   dtype=torch.long, device=sst.device)
        ddim_scheduler.set_variables(perlin_mask, init_timestep)
        ddim_scheduler.mask_idx = ddim_scheduler.b_t.nonzero(as_tuple=True)

        for i, t in enumerate(ddim_scheduler.timesteps):
            t_batch = torch.full((B,), t, dtype=torch.long, device=sst.device)

            # 已知区域用 clean SST，缺失区域保留当前噪声状态
            noisy_input = noisy_sst * perlin_mask + sst * (1 - perlin_mask)
            noisy_input = torch.cat([noisy_input, era5, land_mask], dim=1)

            # 逐像素时间步映射
            beta_bar = 1 - ddim_scheduler.alphas_cumprod
            beta_bar = torch.hstack(
                (torch.tensor([0.0]), beta_bar[:ddim_scheduler.mask_steps])
            ).to(sst.device)
            dist    = torch.abs(ddim_scheduler.b_t_bar.view(-1, 1) - beta_bar[None, :])
            idx_low = torch.argmin(dist, axis=1)
            timesteps_pix = idx_low.float().view(B, 1, H, W)

            model_output = model(noisy_input, timesteps_pix,
                                 geo_emb=geo_emb, return_dict=False)[0]

            # ---- 手动执行 DDIM update，绕过 step() 内部的 set_variables ----
            # 避免 step() 内部用标量/0-dim prev_t 调用 set_variables 导致的
            # 形状不匹配和设备不一致问题。

            # 计算 prev_t_batch（[B] 形状）
            if i + 1 < len(ddim_scheduler.timesteps):
                prev_t_val = ddim_scheduler.timesteps[i + 1].item()
            else:
                prev_t_val = -1
            prev_t_batch = torch.full((B,), prev_t_val, dtype=torch.long, device=sst.device)

            # 当前时间步的 alpha
            ddim_scheduler.set_variables(perlin_mask, t_batch)
            alpha_prod_t = ddim_scheduler.a_t_bar.clone()

            # 前一时间步的 alpha
            if prev_t_val < 0:
                alpha_prod_t_prev = torch.ones_like(alpha_prod_t)
            elif t.item() >= ddim_scheduler.mask_steps and prev_t_val < ddim_scheduler.mask_steps:
                alpha_prod_t_prev = 1 - ddim_scheduler.nu * perlin_mask
            else:
                ddim_scheduler.set_variables(perlin_mask, prev_t_batch)
                alpha_prod_t_prev = ddim_scheduler.a_t_bar.clone()
                ddim_scheduler.set_variables(perlin_mask, t_batch)  # 恢复当前步

            beta_prod_t      = 1 - alpha_prod_t
            beta_prod_t_prev = 1 - alpha_prod_t_prev
            current_alpha_t  = alpha_prod_t / alpha_prod_t_prev.clamp(min=1e-20)
            current_beta_t   = 1 - current_alpha_t

            # 预测类型解码
            if ddim_scheduler.config.prediction_type == "v_prediction":
                pred_original_sample = (alpha_prod_t**0.5) * noisy_sst - (beta_prod_t**0.5) * model_output
                pred_epsilon         = (alpha_prod_t**0.5) * model_output + (beta_prod_t**0.5) * noisy_sst
            elif ddim_scheduler.config.prediction_type == "epsilon":
                pred_original_sample = (noisy_sst - beta_prod_t**0.5 * model_output) / alpha_prod_t**0.5
                pred_epsilon         = model_output
            else:
                raise ValueError(f"Unknown prediction_type: {ddim_scheduler.config.prediction_type}")

            # clip predicted x_0
            if ddim_scheduler.config.clip_sample:
                pred_original_sample = pred_original_sample.clamp(
                    -ddim_scheduler.config.clip_sample_range,
                    ddim_scheduler.config.clip_sample_range,
                )

            # DDIM update（eta=0，确定性采样）
            pred_sample_direction = beta_prod_t_prev.clamp(min=0) ** 0.5 * pred_epsilon
            prev_sample = alpha_prod_t_prev**0.5 * pred_original_sample + pred_sample_direction
            noisy_sst = torch.where(current_beta_t == 0, noisy_sst, prev_sample)

        pred = noisy_sst  # 去噪完成后即为重建结果

        # ---- RMSE 计算（反归一化到 Kelvin）----
        pred_k = (pred.float() + 1.0) / 2.0 * t_scale + t_min
        sst_k  = (sst.float()  + 1.0) / 2.0 * t_scale + t_min

        valid      = static_valid.float()
        diff2      = ((pred_k - sst_k) ** 2) * valid
        rmse_global = torch.sqrt(diff2.sum() / valid.sum().clamp(min=1))

        inpaint_valid = perlin_mask * static_valid
        diff2_inp     = ((pred_k - sst_k) ** 2) * inpaint_valid
        rmse_inpaint  = torch.sqrt(diff2_inp.sum() / inpaint_valid.sum().clamp(min=1))

        all_rmse_global.append(rmse_global.item())
        all_rmse_inpaint.append(rmse_inpaint.item())

        # ---- 可视化（只取第一个batch的前N个样本）----
        if not vis_saved:
            _save_vis(
                sst=sst, era5=era5, land_mask=land_mask,
                perlin_mask=perlin_mask, pred=pred,
                t_min=t_min, t_scale=t_scale,
                n=min(args.vis_num_samples, B),
                save_dir=os.path.join(args.output_dir, "vis"),
                epoch=epoch, global_step=global_step,
            )
            vis_saved = True

    # ---- 汇总指标 ----
    mean_rmse_global  = float(np.mean(all_rmse_global))
    mean_rmse_inpaint = float(np.mean(all_rmse_inpaint))
    std_rmse_global   = float(np.std(all_rmse_global))
    std_rmse_inpaint  = float(np.std(all_rmse_inpaint))

    accelerator.log({
        "val_rmse_global":      mean_rmse_global,
        "val_rmse_inpaint":     mean_rmse_inpaint,
        "val_rmse_global_std":  std_rmse_global,
        "val_rmse_inpaint_std": std_rmse_inpaint,
    }, step=global_step)

    logger.info(
        f"[Validation] Epoch {epoch} Step {global_step} | "
        f"RMSE(global)={mean_rmse_global:.4f}±{std_rmse_global:.4f} K | "
        f"RMSE(inpaint)={mean_rmse_inpaint:.4f}±{std_rmse_inpaint:.4f} K"
    )

    model.train()
    geo_embedding.train()


