def _save_vis(sst, era5, land_mask, perlin_mask, pred,
              t_min, t_scale, n, save_dir, epoch, global_step):
    """
    保存对比图：原始SST | Perlin掩膜 | noisy输入（掩膜后） | 重建SST | 误差图
    每个样本一行，共 n 行，保存为单张 PNG。
    """
    os.makedirs(save_dir, exist_ok=True)

    # 反归一化到 Kelvin，转为 CPU numpy
    def to_kelvin(t):
        return ((t.float() + 1.0) / 2.0 * t_scale + t_min).cpu().numpy()

    sst_k  = to_kelvin(sst[:n, 0])    # [n, H, W]
    pred_k = to_kelvin(pred[:n, 0])   # [n, H, W]
    mask_np   = perlin_mask[:n, 0].float().cpu().numpy()   # [n, H, W]  1=缺失
    land_np   = land_mask[:n, 0].float().cpu().numpy()     # [n, H, W]  1=陆地

    # noisy 输入：已知区域用 clean SST，缺失区域置为 NaN 以显示灰色
    noisy_k = sst_k.copy()
    noisy_k[mask_np > 0.5] = np.nan

    ncols = 5
    fig, axes = plt.subplots(n, ncols, figsize=(ncols * 4, n * 3.5),
                              constrained_layout=True)
    if n == 1:
        axes = axes[np.newaxis, :]

    col_titles = ["GT SST (K)", "Perlin Mask\n(white=missing)",
                  "Input (masked)", "Pred SST (K)", "Error |ΔK|"]

    vmin = float(np.nanpercentile(sst_k, 2))
    vmax = float(np.nanpercentile(sst_k, 98))

    for i in range(n):
        err = np.abs(pred_k[i] - sst_k[i])
        err[land_np[i] > 0.5] = np.nan   # 陆地不显示误差

        imgs   = [sst_k[i], mask_np[i], noisy_k[i], pred_k[i], err]
        cmaps  = ["RdYlBu_r", "gray", "RdYlBu_r", "RdYlBu_r", "hot_r"]
        vmins  = [vmin, 0, vmin, vmin, 0]
        vmaxs  = [vmax, 1, vmax, vmax, float(np.nanpercentile(err, 95) + 1e-3)]

        for j, (img, cmap, v0, v1, title) in enumerate(
                zip(imgs, cmaps, vmins, vmaxs, col_titles)):
            ax = axes[i, j]
            im = ax.imshow(img, cmap=cmap, vmin=v0, vmax=v1, origin="upper")
            plt.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
            if i == 0:
                ax.set_title(title, fontsize=9)
            ax.axis("off")

    fig.suptitle(f"Epoch {epoch}  Step {global_step}", fontsize=11)
    save_path = os.path.join(save_dir, f"epoch{epoch:04d}_step{global_step:07d}.png")
    fig.savefig(save_path, dpi=100)
    plt.close(fig)
    logger.info(f"[Vis] Saved to {save_path}")
