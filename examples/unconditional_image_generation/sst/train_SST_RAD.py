#!/usr/bin/env python
# train_SST_RAD.py
#
# RAD-based SST reconstruction training script.
# Based on train_RAD.py, adapted for multi-channel SST input with:
#   - 3-channel input: [noisy_SST, ERA5, LandMask]
#   - 1-channel output: SST
#   - Geo-Temporal class conditioning
#   - ERA5 dropout (10% probability)
#   - Curriculum mask annealing (3-stage)
#   - Loss restricted to: Perlin-masked ∩ ocean ∩ QL=5 pixels
#   - v-prediction + Min-SNR loss
#   - EMA model
#   - DDIM inference for validation
#   - Validation set month filtering (e.g. 2023 Jan-Jun)
#   - Rich training logging + visualization

